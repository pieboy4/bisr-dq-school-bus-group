alter table public.school_years enable row level security;
alter table public.school_closures enable row level security;
revoke all on public.school_years from anon, authenticated;
revoke all on public.school_closures from anon, authenticated;
grant select on public.school_years to anon, authenticated;
grant select on public.school_closures to anon, authenticated;
drop policy if exists "school years readable" on public.school_years;
