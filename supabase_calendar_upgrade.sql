-- BISR DQ School Bus Group - V1 to V1.1 calendar upgrade
-- Use this only if the V1 children/bus_votes database is already installed.

create table if not exists public.school_years (
  id bigint generated by default as identity primary key,
  label text not null unique,
  start_date date not null,
  end_date date not null,
  updated_at timestamptz not null default now(),
  constraint school_year_range check (end_date >= start_date)
);

create table if not exists public.school_closures (
  id bigint generated by default as identity primary key,
  start_date date not null,
  end_date date not null,
  label text not null,
  category text not null default 'holiday',
  updated_at timestamptz not null default now(),
  constraint school_closure_range check (end_date >= start_date),
  constraint school_closure_unique unique(start_date,end_date,label)
);

create index if not exists school_closures_date_idx on public.school_closures(start_date,end_date);


create or replace function public.set_bus_vote(
  p_date date,
  p_child_id uuid,
  p_journey text,
  p_value boolean
) returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_journey not in ('morning','afternoon') then
    raise exception 'Invalid journey';
  end if;
  if extract(dow from p_date) in (5,6) then
    raise exception 'No bus service on Friday or Saturday';
  end if;
  if not exists (select 1 from public.school_years y where p_date between y.start_date and y.end_date) then
    raise exception 'Date is outside the published BISR school term';
  end if;
  if exists (select 1 from public.school_closures c where p_date between c.start_date and c.end_date) then
    raise exception 'No bus service on a BISR school closure';
  end if;
  insert into public.bus_votes(service_date, child_id, morning, afternoon)
  values (
    p_date,
    p_child_id,
    case when p_journey='morning' then p_value else null end,
    case when p_journey='afternoon' then p_value else null end
  )
  on conflict (service_date, child_id) do update
  set morning = case when p_journey='morning' then excluded.morning else public.bus_votes.morning end,
      afternoon = case when p_journey='afternoon' then excluded.afternoon else public.bus_votes.afternoon end,
      updated_at = now();
end;
$$;

